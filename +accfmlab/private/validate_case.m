function validate_case(raw, settings)
% Validate normalized MATPOWER v2 data before admitting it to AC-CFM.
    define_constants;
    assert(isstruct(raw) && isscalar(raw) && all(isfield(raw, ...
        {'version','baseMVA','bus','gen','branch'})) && (ischar(raw.version) || isstring(raw.version)) && isscalar(string(raw.version)) && strcmp(raw.version,'2'), ...
        'ACCFMLab:CaseFormat','Expected a normalized MATPOWER v2 case struct.');
    assert(isnumeric(raw.baseMVA) && isreal(raw.baseMVA) && isscalar(raw.baseMVA) && ...
        isfinite(raw.baseMVA) && raw.baseMVA>0,'ACCFMLab:CaseFormat','baseMVA must be a finite positive scalar.');
    for spec = {'bus',VMIN; 'gen',PMIN; 'branch',ANGMAX}.'
        field = spec{1};
        values = raw.(field);
        assert(isnumeric(values) && isreal(values) && ismatrix(values) && size(values,2)>=spec{2}, ...
            'ACCFMLab:CaseFormat','%s must be a real matrix with at least %d columns.',field,spec{2});
    end
    b = raw.bus; g = raw.gen; l = raw.branch;
    numbers = b(:,BUS_I);
    assert(all(isfinite(numbers) & numbers>0 & numbers==fix(numbers)) && ...
        numel(unique(numbers))==numel(numbers),'ACCFMLab:CaseFormat', ...
        'BUS_I must contain distinct positive integer bus numbers.');
    assert(all(ismember(b(:,BUS_TYPE),[PQ PV REF NONE])) && ...
        all(isfinite(b(:,[PD QD GS BS BUS_AREA VM VA BASE_KV ZONE])),'all') && ...
        all(b(:,VM)>=0 & b(:,BASE_KV)>=0 & b(:,VMIN)>=0 & b(:,VMIN)<=b(:,VMAX)), ...
        'ACCFMLab:CaseFormat','Invalid bus type, electrical parameter or voltage bounds.');
    generatorCols = intersect([PG QG VG MBASE GEN_STATUS PC1 PC2 QC1MIN QC1MAX QC2MIN QC2MAX], ...
        1:size(g,2));
    assert(all(ismember(g(:,GEN_BUS),numbers)) && ...
        all(isfinite(g(:,generatorCols)),'all') && ...
        all(g(:,VG)>=0 & (g(:,GEN_STATUS)<=0 | g(:,VG)>0) & g(:,MBASE)>=0) && ...
        all(g(:,PMIN)<=g(:,PMAX) & g(:,PMIN)<Inf & g(:,PMAX)>-Inf & ...
            g(:,QMIN)<=g(:,QMAX) & g(:,QMIN)<Inf & g(:,QMAX)>-Inf), ...
        'ACCFMLab:CaseFormat','Invalid generator bus reference, electrical parameter or P/Q bounds.');
    if size(g,2)>=PC1
        % Use MATPOWER's own capability-curve admissibility rules on a copy.
        capability = g;
        if size(capability,2)<QC2MAX
            capability(:,QC2MAX) = 0;
        end
        try
            hasPQcap(capability);
        catch err
            error('ACCFMLab:CaseFormat','Invalid P/Q capability curve: %s',err.message);
        end
    end
    ends = l(:,[F_BUS T_BUS]);
    assert(all(ismember(ends,numbers),'all') && all(ismember(l(:,BR_STATUS),[0 1])) && ...
        all(isfinite(l(:,[BR_R BR_X BR_B TAP SHIFT])),'all') && ...
        all(l(:,[RATE_A RATE_B RATE_C])>=0,'all') && ...
        all(l(:,ANGMIN)<=l(:,ANGMAX) | l(:,ANGMIN)<=-360 | l(:,ANGMAX)>=360) && ...
        all(l(:,ANGMIN)<Inf & l(:,ANGMAX)>-Inf), ...
        'ACCFMLab:CaseFormat','Invalid branch endpoint, electrical parameter, status, rating or angle bounds.');

    if isfield(raw,'gentype')
        types = raw.gentype;
        assert(iscellstr(types) && (isvector(types) || isempty(types)) && numel(types)==size(g,1), ...
            'ACCFMLab:CaseFormat','gentype must contain one character vector per generator row.');
        assert(isempty(types) || size(types,2)==1, ...
            'ACCFMLab:CaseUnsupported','Recovery load2disp requires gentype as a column cell array.');
    end
    if isfield(raw,'gencost')
        costs = raw.gencost;
        assert(isnumeric(costs) && isreal(costs) && ismatrix(costs) && size(costs,2)>=5 && ...
            ismember(size(costs,1),[size(g,1),2*size(g,1)]) && ...
            all(isfinite(costs(:,1:4)),'all'), ...
            'ACCFMLab:CaseFormat','gencost must have one or two rows per generator, with a valid header.');
        for n = 1:size(costs,1)
            model = costs(n,MODEL);
            count = costs(n,NCOST);
            assert(ismember(model,[PW_LINEAR POLYNOMIAL]) && count>=1 && count==fix(count), ...
                'ACCFMLab:CaseFormat','Invalid cost model or term count at gencost row %d.',n);
            width = count*(1+(model==PW_LINEAR));
            assert(size(costs,2)>=COST-1+width && all(isfinite(costs(n,COST:COST-1+width))), ...
                'ACCFMLab:CaseFormat','Missing or nonfinite cost terms at gencost row %d.',n);
            if model==PW_LINEAR
                assert(count>=2 && all(diff(costs(n,COST:2:COST-1+width))>0), ...
                    'ACCFMLab:CaseFormat','Piecewise linear costs require increasing breakpoints at row %d.',n);
            end
        end
    end

    online = l(:,BR_STATUS)==1;
    active = g(:,GEN_STATUS)>0;
    assert(~isempty(b) && all(b(:,BUS_TYPE)~=NONE) && nnz(b(:,BUS_TYPE)==REF)==1, ...
        'ACCFMLab:CaseUnsupported','The platform requires an energized input with one reference bus.');
    assert(all(b(:,PD)>=0) && sum(b(:,PD))>0 && all(g(:,PMIN)>=0), ...
        'ACCFMLab:CaseUnsupported','Use fixed loads with nonnegative PD and positive total demand, and nonnegative generator PMIN for recovery.');
    assert(any(active) && all(g(active,GEN_STATUS)==1) && all(isfinite(g(active,PMAX))), ...
        'ACCFMLab:CaseUnsupported','AC-CFM requires online GEN_STATUS=1 and finite online PMAX.');
    assert(isempty(settings.grid_forming) || isfield(raw,'gentype'), ...
        'ACCFMLab:GridForming','A configured grid-forming filter requires case gentype data.');
    assert(any(online) && all(isfinite(l(online,RATE_A)) & l(online,RATE_A)>0) && ...
        all(l(online,BR_R)~=0 | l(online,BR_X)~=0), ...
        'ACCFMLab:CaseUnsupported','AC-CFM requires active branches with finite positive RATE_A and nonzero impedance.');
    assert(isfield(raw,'gencost') && size(raw.gencost,1)==size(g,1) && size(raw.gencost,2)>=6, ...
        'ACCFMLab:CaseUnsupported','Recovery load2disp requires one active-power cost row per generator and at least six columns.');
    [groups,isolated] = find_islands(raw);
    assert(numel(groups)==1 && isempty(isolated),'ACCFMLab:CaseUnsupported', ...
        'The input network must be connected with no isolated bus.');
end
